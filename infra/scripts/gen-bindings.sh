#!/usr/bin/env bash
# infra/scripts/gen-bindings.sh
# Generate TypeScript bindings from compiled Soroban contracts into packages/contracts-client.
# Idempotent — safe to re-run.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
WASM_DIR="${REPO_ROOT}/contracts/target/wasm32v1-none/release"
CLIENT_PKG_DIR="${REPO_ROOT}/packages/contracts-client"
GENERATED_DIR="${CLIENT_PKG_DIR}/src/generated"

echo "📜  gen-bindings — Generating TypeScript bindings for Soroban contracts"

mkdir -p "${GENERATED_DIR}"

# Map of wasm file basename (without .wasm) to output directory name
CONTRACTS=("issuer_registry:issuer-registry" "credential_status:credential-status" "consent_registry:consent-registry" "correction_tracker:correction-tracker")

for ENTRY in "${CONTRACTS[@]}"; do
  WASM_NAME="${ENTRY%%:*}"
  OUT_NAME="${ENTRY##*:}"
  WASM_FILE="${WASM_DIR}/${WASM_NAME}.wasm"

  if [[ -f "${WASM_FILE}" ]]; then
    echo "  ⚙️  Generating bindings for ${WASM_NAME} -> ${OUT_NAME} ..."
    stellar contract bindings typescript \
      --wasm "${WASM_FILE}" \
      --output-dir "${GENERATED_DIR}/${OUT_NAME}" \
      --overwrite >/dev/null 2>&1 || true

    # Clean up Timepoint import if generated by CLI template
    if [[ -f "${GENERATED_DIR}/${OUT_NAME}/src/index.ts" ]]; then
      sed -i 's/Timepoint,//g' "${GENERATED_DIR}/${OUT_NAME}/src/index.ts" 2>/dev/null || true
    fi
  else
    echo "  ℹ️  Wasm not found for ${WASM_NAME} at ${WASM_FILE}, skipping"
  fi
done

echo "  📦  Building @oneid/contracts-client ..."
cd "${CLIENT_PKG_DIR}"
pnpm build

echo "✅  gen-bindings complete"
