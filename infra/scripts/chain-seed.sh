#!/usr/bin/env bash
# infra/scripts/chain-seed.sh
# Register platform admin, demo issuer, and two demo verifiers (mock anchor, mock fintech) in issuer-registry.
# README §10.3 — pnpm chain:seed
# Idempotent — re-running will not fail or duplicate.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
NETWORK="${1:-${STELLAR_NETWORK:-local}}"
DEPLOYMENTS_FILE="${REPO_ROOT}/deployments/${NETWORK}.json"
SEEDED_FILE="${REPO_ROOT}/deployments/seeded-${NETWORK}.json"

echo "🌱  chain:seed — network: ${NETWORK}"

# Load .env or .env.local
if [[ -f "${REPO_ROOT}/.env.local" ]]; then
  # shellcheck disable=SC2046
  export $(grep -v '^#' "${REPO_ROOT}/.env.local" | grep -v '^$' | xargs 2>/dev/null || true)
fi

# Ensure deployment manifest exists
if [[ ! -f "${DEPLOYMENTS_FILE}" ]]; then
  echo "  Deploying contracts first ..."
  "${SCRIPT_DIR}/deploy-contracts.sh" "${NETWORK}"
fi

ISSUER_REGISTRY_ID=$(grep -o '"issuerRegistry": "[^"]*"' "${DEPLOYMENTS_FILE}" | cut -d'"' -f4 || true)
CREDENTIAL_STATUS_ID=$(grep -o '"credentialStatus": "[^"]*"' "${DEPLOYMENTS_FILE}" | cut -d'"' -f4 || true)

# Resolve or generate demo addresses
get_or_default_addr() {
  local KEY_NAME="$1"
  local DEFAULT_ADDR="$2"
  local ADDR=""
  ADDR=$(stellar keys address "${KEY_NAME}" 2>/dev/null || true)
  if [[ -z "${ADDR}" ]]; then
    ADDR="${DEFAULT_ADDR}"
  fi
  echo "${ADDR}"
}

ADMIN_ADDR=$(get_or_default_addr "admin" "GADMINONEIDDEMOPLATFORMADMIN00000000000000000000000000000000")
ISSUER_ADDR=$(get_or_default_addr "issuer-demo" "GISSUERONEIDDEMOISSUER0000000000000000000000000000000000000")
ANCHOR_ADDR=$(get_or_default_addr "verifier-anchor" "GANCHORONEIDDEMOANCHOR0000000000000000000000000000000000000")
FINTECH_ADDR=$(get_or_default_addr "verifier-fintech" "GFINTECHONEIDDEMOFINTECH00000000000000000000000000000000000")

echo "  Admin address:    ${ADMIN_ADDR}"
echo "  Demo Issuer:      ${ISSUER_ADDR}"
echo "  Mock Anchor:      ${ANCHOR_ADDR}"
echo "  Mock Fintech:     ${FINTECH_ADDR}"

# Write seeded registry manifest for offline reading / TypeScript client verification
NOW_TS=$(date +%s)
cat > "${SEEDED_FILE}" <<EOF
{
  "_comment": "Auto-generated by chain-seed.sh — source of truth for seeded accounts",
  "network": "${NETWORK}",
  "adminAddress": "${ADMIN_ADDR}",
  "issuerRegistryId": "${ISSUER_REGISTRY_ID}",
  "credentialStatusId": "${CREDENTIAL_STATUS_ID}",
  "entities": {
    "${ISSUER_ADDR}": {
      "address": "${ISSUER_ADDR}",
      "role": "Issuer",
      "name": "ONEiD Demo Issuer",
      "homeDomain": "issuer.demo.oneid.local",
      "status": "Active",
      "registeredAt": ${NOW_TS}
    },
    "${ANCHOR_ADDR}": {
      "address": "${ANCHOR_ADDR}",
      "role": "Verifier",
      "name": "Mock Anchor",
      "homeDomain": "anchor.demo.oneid.local",
      "status": "Active",
      "registeredAt": ${NOW_TS}
    },
    "${FINTECH_ADDR}": {
      "address": "${FINTECH_ADDR}",
      "role": "Verifier",
      "name": "Mock Fintech",
      "homeDomain": "fintech.demo.oneid.local",
      "status": "Active",
      "registeredAt": ${NOW_TS}
    }
  }
}
EOF

echo "  📄  Wrote seeded registry to ${SEEDED_FILE}"

# If RPC is healthy, submit cross-contract calls to chain
RPC_URL="${STELLAR_RPC_URL:-http://localhost:8000/soroban/rpc}"
if [[ "${NETWORK}" == "testnet" ]]; then
  RPC_URL="${STELLAR_RPC_URL:-https://soroban-testnet.stellar.org}"
fi

if curl -sf -X POST -H "Content-Type: application/json" -d '{"jsonrpc":"2.0","id":1,"method":"getHealth"}' "${RPC_URL}" 2>/dev/null | grep -q '"status":"healthy"'; then
  echo "  🌐  Soroban RPC is online. Invoking chain seed transactions ..."

  # 1. Init issuer-registry (idempotent, ignore if already initialised)
  stellar contract invoke \
    --id "${ISSUER_REGISTRY_ID}" \
    --source admin \
    --network "${NETWORK}" \
    -- init --admin "${ADMIN_ADDR}" 2>/dev/null || true

  # 2. Register demo issuer
  stellar contract invoke \
    --id "${ISSUER_REGISTRY_ID}" \
    --source admin \
    --network "${NETWORK}" \
    -- register --entity "{\"address\":\"${ISSUER_ADDR}\",\"role\":0,\"name\":\"ONEiD Demo Issuer\",\"home_domain\":\"issuer.demo.oneid.local\",\"status\":0,\"registered_at\":0}" 2>/dev/null || true

  # 3. Register mock anchor
  stellar contract invoke \
    --id "${ISSUER_REGISTRY_ID}" \
    --source admin \
    --network "${NETWORK}" \
    -- register --entity "{\"address\":\"${ANCHOR_ADDR}\",\"role\":1,\"name\":\"Mock Anchor\",\"home_domain\":\"anchor.demo.oneid.local\",\"status\":0,\"registered_at\":0}" 2>/dev/null || true

  # 4. Register mock fintech
  stellar contract invoke \
    --id "${ISSUER_REGISTRY_ID}" \
    --source admin \
    --network "${NETWORK}" \
    -- register --entity "{\"address\":\"${FINTECH_ADDR}\",\"role\":1,\"name\":\"Mock Fintech\",\"home_domain\":\"fintech.demo.oneid.local\",\"status\":0,\"registered_at\":0}" 2>/dev/null || true

  # 5. Init credential-status with issuer-registry ID
  stellar contract invoke \
    --id "${CREDENTIAL_STATUS_ID}" \
    --source admin \
    --network "${NETWORK}" \
    -- init --issuer_registry "${ISSUER_REGISTRY_ID}" 2>/dev/null || true
fi

echo "✅  chain:seed completed successfully"
