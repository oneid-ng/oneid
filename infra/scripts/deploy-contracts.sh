#!/usr/bin/env bash
# infra/scripts/deploy-contracts.sh
# Build and deploy Soroban contracts to a given network.
# Writes contract IDs to deployments/<network>.json.
# Usage: ./deploy-contracts.sh [local|testnet]
# NOT FULLY IMPLEMENTED — stub that deploys hello-world only.
# Full contract deployment arrives on Day 2 with the real contracts.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
NETWORK="${1:-${STELLAR_NETWORK:-local}}"
DEPLOYMENTS_FILE="${REPO_ROOT}/deployments/${NETWORK}.json"

echo "🚀  deploy-contracts — network: ${NETWORK}"
echo "    NOTE: Full deployment arrives Day 2. This stub deploys hello-world only."

mkdir -p "${REPO_ROOT}/deployments"

# Build contracts
cd "${REPO_ROOT}/contracts"
stellar contract build 2>&1

# Deploy hello-world (scaffold — to be removed Day 2)
WASM="target/wasm32v1-none/release/hello_world.wasm"
if [[ ! -f "${WASM}" ]]; then
  echo "❌  WASM not found at ${WASM}. Run 'pnpm contracts:build' first."
  exit 1
fi

HELLO_ID=$(stellar contract deploy \
  --wasm "${WASM}" \
  --source admin \
  --network "${NETWORK}" \
  --ignore-checks 2>/dev/null || true)

if [[ -z "${HELLO_ID}" ]]; then
  echo "⚠  hello-world deploy returned empty ID — chain may not be ready"
  HELLO_ID="DEPLOY_FAILED"
fi

# Write deployment manifest
cat > "${DEPLOYMENTS_FILE}" <<EOF
{
  "_comment": "Auto-generated by deploy-contracts.sh — do not edit manually",
  "_network": "${NETWORK}",
  "helloWorld": "${HELLO_ID}",
  "issuerRegistry": "NOT_DEPLOYED_YET",
  "credentialStatus": "NOT_DEPLOYED_YET",
  "consentRegistry": "NOT_DEPLOYED_YET",
  "correctionTracker": "NOT_DEPLOYED_YET"
}
EOF

echo "✅  Deployment manifest written to ${DEPLOYMENTS_FILE}"
cat "${DEPLOYMENTS_FILE}"
